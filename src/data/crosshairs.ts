export function getCrosshairById(id: string): CrosshairConfig | undefined {
  return BUILTIN_CROSSHAIRS.find((ch) => ch.id === id);
}

export function getCrosshairsByCategory(category: Category): CrosshairConfig[] {
  return BUILTIN_CROSSHAIRS.filter((ch) => ch.category === category);
}

export function searchCrosshairs(query: string): CrosshairConfig[] {
  const lower = query.toLowerCase();
  return BUILTIN_CROSSHAIRS.filter(
    (ch) =>
      ch.name.toLowerCase().includes(lower) ||
      ch.category.toLowerCase().includes(lower) ||
      ch.id.toLowerCase().includes(lower)
  );
}

